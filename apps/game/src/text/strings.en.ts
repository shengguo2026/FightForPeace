/**
 * M10 English base catalogue. Every key here must exist in strings.zh-CN.ts and
 * strings.de.ts (tests/lint/catalogues.test.ts). Prompt tokens `{action:…}` and
 * `{dir:…}` are drawn from each player's own bindings; `{name}` values are filled in.
 * No string names a key or button (tests/lint/prompt-text.test.ts).
 */
type Prefixed<P extends string, T> = { [K in keyof T & string as `${P}${K}`]: string };
function prefixed<P extends string, T extends Record<string, string>>(p: P, o: T): Prefixed<P, T> {
  return Object.fromEntries(Object.entries(o).map(([k, v]) => [p + k, v])) as Prefixed<P, T>;
}


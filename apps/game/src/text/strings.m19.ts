/**
 * The difficulty variants' move names: each variant kit (art = its base kit) repeats its
 * base kit's moves, so its keys take the base kit's translations.
 */
function variantMoves(cat: Catalog): Catalog {
  const out: Record<string, string> = {};
  for (const k of ENEMIES) {
    if (!k.art || k.art === k.id) continue;
    for (const a of k.actions) {
      const text = cat[`enemy.${k.art}.action.${a.id}`];
      if (text) out[`enemy.${k.id}.action.${a.id}`] = text;
    }
  }
  return out;
}


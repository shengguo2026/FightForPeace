const KITS = ['ambusher', 'bruiser', 'trapper', 'raider', 'stalker', 'captain'];

/** Difficulty variants share their base role's moves: each takes the base translation. */
function variantMoves(cat: Catalog): Catalog {
  const out: Record<string, string> = {};
  for (const k of ENEMIES) {
    const base = KITS.find((b) => k.id.startsWith(`${b}-`));
    if (!base) continue;
    for (const a of k.actions) {
      const text = cat[`enemy.${base}.action.${a.id}`];
      if (text) out[`enemy.${k.id}.action.${a.id}`] = text;
    }
  }
  return out;
}


// Generates packages/sim/src/math/sinTable.ts: a quarter-wave sine table with 1,025
// entries, value = round(256 · sin(i · π / 2048)). Run once and commit the output, so the
// simulation never calls Math.sin at runtime.  Usage: node tools/gen-sin-table.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const QUARTER = 1024;
const values = Array.from({ length: QUARTER + 1 }, (_, i) =>
  Math.round(256 * Math.sin((i * Math.PI) / (2 * QUARTER))),
);
const rows = [];
for (let i = 0; i < values.length; i += 16)
  rows.push('  ' + values.slice(i, i + 16).join(', ') + ',');
const out = `// GENERATED by tools/gen-sin-table.mjs. Do not edit by hand.
// Quarter-wave sine table: SIN_QUARTER_TABLE[i] = round(256 · sin(i · π / 2048)), i = 0…1024.
export const SIN_QUARTER_TABLE: readonly number[] = [
${rows.join('\n')}
];
`;
writeFileSync(fileURLToPath(new URL('../packages/sim/src/math/sinTable.ts', import.meta.url)), out);
